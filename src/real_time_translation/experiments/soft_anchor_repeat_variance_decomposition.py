"""h-soft-anchor-repeat-variance-decomposition: does anchoring continuation
translations to the prior batch's own output (soft_anchor_replay) reduce
repeat-to-repeat NE *variance*, not just mean NE?

h-hard-prefix-lock-continuation's result_summary noted in passing that
baseline_replay showed visibly higher repeat-to-repeat NE variance than
soft_anchor_replay/hard_lock (e.g. span 13: 1.0 vs 1.586 across its 2
repeats). h-soft-anchor-generalization-guest-talk independently re-observed
the same pattern on a second, larger clip ("baseline hit NE=0 in only 9/166
repeat-runs vs soft_anchor's 123/166"). Neither formalized this into a
dedicated analysis -- both treated it as an aside while answering their own
primary mean-NE question. This script does the formalization, reusing the
between-vs-within variance decomposition methodology already established in
judge_noise_power_analysis.py's _decompose_zero_effect_variance() (cycle 21):
average within-span variance across spans, never pool raw repeat values
across spans first (that conflates each span's own translation-difficulty
level with true repeat noise, as cycle 21 found for judge-score noise).

Both source replay JSONs already store a `condition_ne` list of exactly
REPEATS=2 raw NE values per span per condition -- this script does pure
arithmetic over those already-recorded numbers. No live Deepgram/Gemini/
OpenAI call of any kind is made; no new experiment JSON is generated by a
live run. hard_lock is excluded from the variance comparison: its
condition_ne is [0.0, 0.0] in every span by construction (the frozen prefix
literally cannot be rewritten), so its variance is trivially and
uninformatively zero, exactly as h-hard-prefix-lock-continuation's own
result_summary already concluded for its mean.

Usage:
  python3 -m real_time_translation.experiments.soft_anchor_repeat_variance_decomposition
"""

from __future__ import annotations

import json
import statistics
from pathlib import Path

SOURCES = {
    "original_clip": Path("experiments/20260919_h_hard_prefix_lock_replay.json"),
    "guest_talk_clip": Path(
        "experiments/20260919_h_soft_anchor_generalization_guest_talk.json"
    ),
}
CONDITIONS = ("baseline_replay", "soft_anchor_replay")
OUT_JSON = Path("experiments/20261022_h_soft_anchor_repeat_variance_decomposition.json")


def _within_span_variance(values: list[float]) -> float | None:
    """Sample variance (ddof=1) of a single span's repeat values. For the
    REPEATS=2 case this is ((v0 - v1) ** 2) / 2, i.e. half the squared
    difference between the two repeats -- but we compute it generically via
    statistics.variance so this still works if REPEATS is ever raised."""
    if len(values) < 2:
        return None
    return statistics.variance(values)


def _analyze_clip(path: Path) -> dict:
    data = json.loads(path.read_text(encoding="utf-8"))
    spans = data["results"]["spans"]
    per_condition: dict[str, dict] = {}
    for condition in CONDITIONS:
        within_variances: list[float] = []
        span_means: list[float] = []
        all_raw_values: list[float] = []
        for span in spans:
            ne_list = span.get("condition_ne", {}).get(condition)
            if not ne_list:
                continue
            defined = [v for v in ne_list if v is not None]
            if len(defined) < 2:
                continue
            within_variances.append(_within_span_variance(defined))
            span_means.append(statistics.mean(defined))
            all_raw_values.extend(defined)
        per_condition[condition] = {
            "num_usable_spans": len(within_variances),
            "mean_within_span_variance": (
                statistics.mean(within_variances) if within_variances else None
            ),
            "median_within_span_variance": (
                statistics.median(within_variances) if within_variances else None
            ),
            "min_within_span_variance": (
                min(within_variances) if within_variances else None
            ),
            "max_within_span_variance": (
                max(within_variances) if within_variances else None
            ),
            "between_span_variance_of_span_means": (
                statistics.variance(span_means) if len(span_means) >= 2 else None
            ),
            "mean_ne_across_spans": (
                statistics.mean(span_means) if span_means else None
            ),
            # naive pooled stdev of all raw repeat values across all spans,
            # reported ONLY for contrast with the within-span figure above --
            # per cycle 21's finding this conflates between-span quality
            # differences with true repeat noise and should not itself be
            # read as "the" repeat-noise estimate.
            "naive_pooled_variance_all_raw_values": (
                statistics.variance(all_raw_values)
                if len(all_raw_values) >= 2
                else None
            ),
        }
    return per_condition


def main() -> None:
    per_clip: dict[str, dict] = {}
    for clip_name, path in SOURCES.items():
        if not path.exists():
            print(f"SKIP {clip_name}: {path} not found")
            continue
        per_clip[clip_name] = _analyze_clip(path)
        print(f"=== {clip_name} ({path}) ===")
        for condition, stats in per_clip[clip_name].items():
            print(
                f"  {condition}: mean_within_span_var="
                f"{stats['mean_within_span_variance']} "
                f"(n={stats['num_usable_spans']} spans), "
                f"between_span_var={stats['between_span_variance_of_span_means']}, "
                f"naive_pooled_var={stats['naive_pooled_variance_all_raw_values']}"
            )

    # Pooled-across-both-clips: average each clip's mean_within_span_variance
    # per condition (equal weight per clip, not per span, so the 83-span
    # guest-talk clip doesn't dominate the pooled figure purely by volume).
    pooled: dict[str, dict] = {}
    for condition in CONDITIONS:
        clip_means = [
            per_clip[c][condition]["mean_within_span_variance"]
            for c in per_clip
            if per_clip[c][condition]["mean_within_span_variance"] is not None
        ]
        pooled[condition] = {
            "mean_of_per_clip_mean_within_span_variance": (
                statistics.mean(clip_means) if clip_means else None
            ),
            "num_clips": len(clip_means),
        }

    print("\n=== pooled across both clips (equal weight per clip) ===")
    for condition, stats in pooled.items():
        print(f"  {condition}: {stats}")

    out = {
        "experiment_name": "h_soft_anchor_repeat_variance_decomposition",
        "input": {
            "type": "retroactive_analysis",
            "sources": {k: str(v) for k, v in SOURCES.items()},
            "note": (
                "Pure arithmetic over condition_ne values already recorded in "
                "two prior replay experiment JSONs (h-hard-prefix-lock-continuation, "
                "h-soft-anchor-generalization-guest-talk). No live Deepgram/Gemini/"
                "OpenAI calls of any kind; no new translation or judge calls."
            ),
        },
        "per_clip": per_clip,
        "pooled_across_clips": pooled,
        "method_note": (
            "Within-span variance is averaged across spans (not raw repeat "
            "values pooled across spans first), per the decomposition "
            "established in judge_noise_power_analysis.py's "
            "_decompose_zero_effect_variance() (cycle 21) -- pooling raw "
            "values first conflates each span's own translation-difficulty "
            "level with true repeat noise. hard_lock intentionally excluded: "
            "its condition_ne is [0.0, 0.0] in every span by construction "
            "(frozen prefix cannot be rewritten), so its variance is zero "
            "trivially and uninformatively, same conclusion as "
            "h-hard-prefix-lock-continuation's own mean-NE result_summary."
        ),
    }
    OUT_JSON.write_text(
        json.dumps(out, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(f"\nWrote {OUT_JSON}")


if __name__ == "__main__":
    main()
